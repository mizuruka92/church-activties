CREATE OR REPLACE VIEW ANALISIS.SUMBANGAN_KHUSUS_PER_WILAYAH
    COMMENT = 'Sumbangan kesempatan khusus per wilayah dan periode. Hanya ringkasan, tidak untuk memeringkat wilayah. Data simulasi.'
AS
