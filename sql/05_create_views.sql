    s.ID_SUMBANGAN,
    k.NAMA_KESEMPATAN,
    k.MUSIM_LITURGI,
    s.PERIODE_MULAI,
    s.PERIODE_SELESAI,
    w.ID_WILAYAH,
    w.NAMA_WILAYAH,
    s.JUMLAH_KELUARGA_PESERTA,
    s.JUMLAH_SUMBANGAN,
    SUM(s.JUMLAH_SUMBANGAN) OVER (PARTITION BY s.ID_KESEMPATAN, s.PERIODE_MULAI) AS TOTAL_SUMBANGAN_SELURUH_WILAYAH,
    s.TANGGAL_PENCATATAN,
