-- 14. Weekly offertory and attendance, annotated with unforeseen events --------------------------------
CREATE OR REPLACE VIEW ANALISIS.KOLEKTE_MINGGUAN_DAN_PERISTIWA
    COMMENT = 'Kolekte dan kehadiran per pekan (Senin sampai Minggu) dengan peristiwa luar biasa, untuk grafik riwayat dan membaca penyimpangan peramalan. Data simulasi.'
AS
WITH KOLEKTE_PER_MISA AS (
    SELECT ID_KEJADIAN_MISA,
           SUM(COALESCE(JUMLAH_HASIL_PENGHITUNGAN, JUMLAH_PENERIMAAN)) AS TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE
    GROUP BY ID_KEJADIAN_MISA
),
PEKANAN AS (
    SELECT
        DATEADD('day', -MOD(DATEDIFF('day', DATE '1900-01-01', k.TANGGAL_MISA), 7), k.TANGGAL_MISA) AS AWAL_PEKAN,
        COUNT(*) AS JUMLAH_MISA_TERLAKSANA,
        SUM(a.JUMLAH_UMAT) AS TOTAL_UMAT,
        SUM(c.TOTAL_KOLEKTE) AS TOTAL_KOLEKTE,
        MIN(a.ID_PERISTIWA) AS ID_PERISTIWA
    FROM DATA_OPERASIONAL.KEJADIAN_MISA k
    JOIN DATA_OPERASIONAL.KEHADIRAN_MISA a
        ON a.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    JOIN KOLEKTE_PER_MISA c
        ON c.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    WHERE k.STATUS_PELAKSANAAN = 'Terlaksana'
    GROUP BY DATEADD('day', -MOD(DATEDIFF('day', DATE '1900-01-01', k.TANGGAL_MISA), 7), k.TANGGAL_MISA)
),
DENGAN_PEMBANDING AS (
    SELECT
        w.AWAL_PEKAN,
        w.JUMLAH_MISA_TERLAKSANA,
        w.TOTAL_UMAT,
        w.TOTAL_KOLEKTE,
        w.ID_PERISTIWA,
        AVG(w.TOTAL_UMAT) OVER (ORDER BY w.AWAL_PEKAN ROWS BETWEEN 8 PRECEDING AND 1 PRECEDING) AS RATA_RATA_UMAT_8_PEKAN_SEBELUMNYA,
        AVG(w.TOTAL_KOLEKTE) OVER (ORDER BY w.AWAL_PEKAN ROWS BETWEEN 8 PRECEDING AND 1 PRECEDING) AS RATA_RATA_KOLEKTE_8_PEKAN_SEBELUMNYA
    FROM PEKANAN w
)
SELECT
    d.AWAL_PEKAN,
    EXTRACT(YEAR FROM d.AWAL_PEKAN) AS TAHUN,
    d.JUMLAH_MISA_TERLAKSANA,
    d.TOTAL_UMAT,
    d.TOTAL_KOLEKTE,
    d.RATA_RATA_UMAT_8_PEKAN_SEBELUMNYA,
    d.RATA_RATA_KOLEKTE_8_PEKAN_SEBELUMNYA,
    CASE WHEN d.RATA_RATA_UMAT_8_PEKAN_SEBELUMNYA IS NULL OR d.RATA_RATA_UMAT_8_PEKAN_SEBELUMNYA = 0 THEN NULL
         ELSE ROUND(100.0 * d.TOTAL_UMAT / d.RATA_RATA_UMAT_8_PEKAN_SEBELUMNYA, 1)
    END AS PERSEN_UMAT_TERHADAP_8_PEKAN_SEBELUMNYA,
    CASE WHEN d.RATA_RATA_KOLEKTE_8_PEKAN_SEBELUMNYA IS NULL OR d.RATA_RATA_KOLEKTE_8_PEKAN_SEBELUMNYA = 0 THEN NULL
         ELSE ROUND(100.0 * d.TOTAL_KOLEKTE / d.RATA_RATA_KOLEKTE_8_PEKAN_SEBELUMNYA, 1)
    END AS PERSEN_KOLEKTE_TERHADAP_8_PEKAN_SEBELUMNYA,
    e.ID_PERISTIWA,
    e.JENIS_PERISTIWA,
    e.NAMA_PERISTIWA,
    e.TINGKAT_GANGGUAN,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DENGAN_PEMBANDING d
LEFT JOIN DATA_OPERASIONAL.PERISTIWA_LUAR_BIASA e
    ON e.ID_PERISTIWA = d.ID_PERISTIWA;

-- 15. Effect of each unforeseen event ---------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.DAMPAK_PERISTIWA_LUAR_BIASA
    COMMENT = 'Kehadiran dan kolekte selama setiap peristiwa luar biasa dibandingkan dengan yang diharapkan dari rata-rata 8 pekan sebelumnya untuk sesi Misa yang sama. Data simulasi.'
AS
WITH KOLEKTE_PER_MISA AS (
    SELECT ID_KEJADIAN_MISA,
           SUM(COALESCE(JUMLAH_HASIL_PENGHITUNGAN, JUMLAH_PENERIMAAN)) AS TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE
    GROUP BY ID_KEJADIAN_MISA
),
MISA AS (
    SELECT k.TANGGAL_MISA, k.STATUS_PELAKSANAAN, j.NAMA_MISA, a.JUMLAH_UMAT, c.TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.KEJADIAN_MISA k
    JOIN MASTER_DATA.JADWAL_MISA j
        ON j.ID_JADWAL_MISA = k.ID_JADWAL_MISA
    LEFT JOIN DATA_OPERASIONAL.KEHADIRAN_MISA a
        ON a.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    LEFT JOIN KOLEKTE_PER_MISA c
        ON c.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    WHERE k.STATUS_PELAKSANAAN IN ('Terlaksana', 'Dibatalkan')
),
BASIS AS (
    -- what a Mass of each session normally brings in the 8 weeks before the event
    SELECT e.ID_PERISTIWA, m.NAMA_MISA,
           AVG(m.JUMLAH_UMAT) AS RATA_RATA_UMAT,
           AVG(m.TOTAL_KOLEKTE) AS RATA_RATA_KOLEKTE
    FROM DATA_OPERASIONAL.PERISTIWA_LUAR_BIASA e
    JOIN MISA m
        ON m.TANGGAL_MISA BETWEEN DATEADD('day', -56, e.TANGGAL_MULAI) AND DATEADD('day', -1, e.TANGGAL_MULAI)
    GROUP BY e.ID_PERISTIWA, m.NAMA_MISA
),
SELAMA AS (
    -- every scheduled Mass inside the event, compared with the normal result of its own session
    SELECT e.ID_PERISTIWA,
           SUM(CASE WHEN m.STATUS_PELAKSANAAN = 'Terlaksana' THEN 1 ELSE 0 END) AS JUMLAH_MISA_TERLAKSANA,
           SUM(CASE WHEN m.STATUS_PELAKSANAAN = 'Dibatalkan' THEN 1 ELSE 0 END) AS JUMLAH_MISA_DIBATALKAN,
           SUM(COALESCE(m.JUMLAH_UMAT, 0)) AS UMAT_AKTUAL,
           SUM(b.RATA_RATA_UMAT) AS UMAT_DIHARAPKAN,
           SUM(COALESCE(m.TOTAL_KOLEKTE, 0)) AS KOLEKTE_AKTUAL,
           SUM(b.RATA_RATA_KOLEKTE) AS KOLEKTE_DIHARAPKAN
    FROM DATA_OPERASIONAL.PERISTIWA_LUAR_BIASA e
    JOIN MISA m
        ON m.TANGGAL_MISA BETWEEN e.TANGGAL_MULAI AND e.TANGGAL_SELESAI
    LEFT JOIN BASIS b
        ON b.ID_PERISTIWA = e.ID_PERISTIWA AND b.NAMA_MISA = m.NAMA_MISA
    GROUP BY e.ID_PERISTIWA
)
SELECT
    e.ID_PERISTIWA,
    e.JENIS_PERISTIWA,
    e.NAMA_PERISTIWA,
    e.TANGGAL_MULAI,
    e.TANGGAL_SELESAI,
    e.TINGKAT_GANGGUAN,
    e.DESKRIPSI,
    d.JUMLAH_MISA_TERLAKSANA,
    d.JUMLAH_MISA_DIBATALKAN,
    d.UMAT_AKTUAL AS UMAT_AKTUAL_SELAMA_PERISTIWA,
    ROUND(d.UMAT_DIHARAPKAN, 0) AS UMAT_DIHARAPKAN,
    ROUND(100.0 * d.UMAT_AKTUAL / NULLIF(d.UMAT_DIHARAPKAN, 0), 1) AS PERSEN_KEHADIRAN_TERHADAP_HARAPAN,
    d.KOLEKTE_AKTUAL AS KOLEKTE_AKTUAL_SELAMA_PERISTIWA,
    ROUND(d.KOLEKTE_DIHARAPKAN, 0) AS KOLEKTE_DIHARAPKAN,
    ROUND(100.0 * d.KOLEKTE_AKTUAL / NULLIF(d.KOLEKTE_DIHARAPKAN, 0), 1) AS PERSEN_KOLEKTE_TERHADAP_HARAPAN,
    ROUND(d.KOLEKTE_DIHARAPKAN - d.KOLEKTE_AKTUAL, 0) AS PERKIRAAN_KOLEKTE_YANG_TIDAK_DITERIMA,
    'Perkiraan kasar: dibandingkan dengan rata-rata 8 pekan sebelumnya untuk sesi Misa yang sama, tanpa koreksi hari gajian dan musim.' AS CATATAN_METODE,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DATA_OPERASIONAL.PERISTIWA_LUAR_BIASA e
LEFT JOIN SELAMA d
    ON d.ID_PERISTIWA = e.ID_PERISTIWA;

-- 16. Offertory pattern within the month (after salary day) -------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.POLA_KOLEKTE_HARI_DALAM_BULAN
    COMMENT = 'Kolekte per umat yang hadir menurut tanggal dalam bulan, per tahun. Pola administrasi (setelah hari gajian), bukan ukuran iman. Data simulasi.'
AS
WITH KOLEKTE_PER_MISA AS (
    SELECT ID_KEJADIAN_MISA,
           SUM(COALESCE(JUMLAH_HASIL_PENGHITUNGAN, JUMLAH_PENERIMAAN)) AS TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE
    GROUP BY ID_KEJADIAN_MISA
)
SELECT
    EXTRACT(YEAR FROM k.TANGGAL_MISA) AS TAHUN,
    EXTRACT(DAY FROM k.TANGGAL_MISA) AS HARI_DALAM_BULAN,
    CASE WHEN EXTRACT(DAY FROM k.TANGGAL_MISA) <= 7 THEN 'Tanggal 1-7'
         WHEN EXTRACT(DAY FROM k.TANGGAL_MISA) <= 14 THEN 'Tanggal 8-14'
         WHEN EXTRACT(DAY FROM k.TANGGAL_MISA) <= 21 THEN 'Tanggal 15-21'
         ELSE 'Tanggal 22-31'
    END AS KELOMPOK_TANGGAL,
    COUNT(*) AS JUMLAH_MISA,
    SUM(a.JUMLAH_UMAT) AS TOTAL_UMAT,
    SUM(c.TOTAL_KOLEKTE) AS TOTAL_KOLEKTE,
    ROUND(1.0 * SUM(c.TOTAL_KOLEKTE) / NULLIF(SUM(a.JUMLAH_UMAT), 0), 0) AS KOLEKTE_PER_UMAT,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DATA_OPERASIONAL.KEJADIAN_MISA k
JOIN DATA_OPERASIONAL.KEHADIRAN_MISA a
    ON a.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
JOIN KOLEKTE_PER_MISA c
    ON c.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
WHERE k.STATUS_PELAKSANAAN = 'Terlaksana'
GROUP BY EXTRACT(YEAR FROM k.TANGGAL_MISA), EXTRACT(DAY FROM k.TANGGAL_MISA);

-- 17. Correlation of offertory with attendance and with the day of the month -----------------------------------------
CREATE OR REPLACE VIEW ANALISIS.KORELASI_KOLEKTE_KEHADIRAN
    COMMENT = 'Korelasi kolekte dengan jumlah umat dan dengan tanggal dalam bulan, per tahun dan sesi Misa. Data simulasi.'
AS
WITH KOLEKTE_PER_MISA AS (
    SELECT ID_KEJADIAN_MISA,
           SUM(COALESCE(JUMLAH_HASIL_PENGHITUNGAN, JUMLAH_PENERIMAAN)) AS TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE
    GROUP BY ID_KEJADIAN_MISA
)
SELECT
    EXTRACT(YEAR FROM k.TANGGAL_MISA) AS TAHUN,
    j.NAMA_MISA,
    COUNT(*) AS JUMLAH_MISA,
    ROUND(CORR(a.JUMLAH_UMAT, c.TOTAL_KOLEKTE), 3) AS KORELASI_KOLEKTE_DENGAN_UMAT,
    ROUND(REGR_R2(c.TOTAL_KOLEKTE, a.JUMLAH_UMAT), 3) AS R_KUADRAT_KOLEKTE_DARI_UMAT,
    ROUND(REGR_SLOPE(c.TOTAL_KOLEKTE, a.JUMLAH_UMAT), 0) AS TAMBAHAN_KOLEKTE_PER_UMAT,
    ROUND(CORR(EXTRACT(DAY FROM k.TANGGAL_MISA), 1.0 * c.TOTAL_KOLEKTE / a.JUMLAH_UMAT), 3) AS KORELASI_TANGGAL_DENGAN_KOLEKTE_PER_UMAT,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DATA_OPERASIONAL.KEJADIAN_MISA k
JOIN DATA_OPERASIONAL.KEHADIRAN_MISA a
    ON a.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
JOIN KOLEKTE_PER_MISA c
    ON c.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
JOIN MASTER_DATA.JADWAL_MISA j
    ON j.ID_JADWAL_MISA = k.ID_JADWAL_MISA
WHERE k.STATUS_PELAKSANAAN = 'Terlaksana'
GROUP BY EXTRACT(YEAR FROM k.TANGGAL_MISA), j.NAMA_MISA;

-- 18. Income versus outcome per month ------------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.PEMASUKAN_PENGELUARAN_BULANAN
    COMMENT = 'Pemasukan (kolekte, sumbangan khusus) dan pengeluaran program per bulan, dengan peristiwa luar biasa. Data simulasi.'
AS
WITH KOLEKTE AS (
    SELECT p.ID_PERIODE_PELAPORAN,
           SUM(COALESCE(c.JUMLAH_HASIL_PENGHITUNGAN, c.JUMLAH_PENERIMAAN)) AS NILAI
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE c
    JOIN DATA_OPERASIONAL.KEJADIAN_MISA k
        ON k.ID_KEJADIAN_MISA = c.ID_KEJADIAN_MISA
    JOIN MASTER_DATA.REFERENSI_PERIODE_PELAPORAN p
        ON k.TANGGAL_MISA BETWEEN p.TANGGAL_MULAI AND p.TANGGAL_SELESAI
    GROUP BY p.ID_PERIODE_PELAPORAN
),
SUMBANGAN AS (
    SELECT p.ID_PERIODE_PELAPORAN, SUM(g.JUMLAH_SUMBANGAN) AS NILAI
    FROM DATA_OPERASIONAL.SUMBANGAN_KELUARGA g
    JOIN MASTER_DATA.REFERENSI_PERIODE_PELAPORAN p
        ON g.TANGGAL_SUMBANGAN BETWEEN p.TANGGAL_MULAI AND p.TANGGAL_SELESAI
    GROUP BY p.ID_PERIODE_PELAPORAN
),
PENGELUARAN AS (
    SELECT p.ID_PERIODE_PELAPORAN, SUM(x.JUMLAH_PENGELUARAN) AS NILAI
    FROM DATA_OPERASIONAL.REALISASI_PENGELUARAN x
    JOIN MASTER_DATA.REFERENSI_PERIODE_PELAPORAN p
        ON x.TANGGAL_PENGELUARAN BETWEEN p.TANGGAL_MULAI AND p.TANGGAL_SELESAI
    GROUP BY p.ID_PERIODE_PELAPORAN
),
PERISTIWA AS (
    SELECT p.ID_PERIODE_PELAPORAN,
           MIN(e.NAMA_PERISTIWA) AS NAMA_PERISTIWA,
           MIN(e.JENIS_PERISTIWA) AS JENIS_PERISTIWA,
           MIN(e.TINGKAT_GANGGUAN) AS TINGKAT_GANGGUAN
    FROM MASTER_DATA.REFERENSI_PERIODE_PELAPORAN p
    JOIN DATA_OPERASIONAL.PERISTIWA_LUAR_BIASA e
        ON e.TANGGAL_MULAI <= p.TANGGAL_SELESAI AND e.TANGGAL_SELESAI >= p.TANGGAL_MULAI
    GROUP BY p.ID_PERIODE_PELAPORAN
)
SELECT
    p.ID_PERIODE_PELAPORAN,
    p.TAHUN,
    p.BULAN,
    p.NAMA_PERIODE,
    CASE WHEN p.TANGGAL_SELESAI <= i.TANGGAL_SNAPSHOT THEN 'Lengkap' ELSE 'Berjalan' END AS STATUS_PERIODE,
    COALESCE(k.NILAI, 0) AS PEMASUKAN_KOLEKTE,
    COALESCE(s.NILAI, 0) AS PEMASUKAN_SUMBANGAN_KHUSUS,
    COALESCE(k.NILAI, 0) + COALESCE(s.NILAI, 0) AS TOTAL_PEMASUKAN,
    COALESCE(x.NILAI, 0) AS PENGELUARAN_PROGRAM,
    COALESCE(k.NILAI, 0) - COALESCE(x.NILAI, 0) AS SELISIH_KOLEKTE_VS_PENGELUARAN,
    COALESCE(k.NILAI, 0) + COALESCE(s.NILAI, 0) - COALESCE(x.NILAI, 0) AS SELISIH_TOTAL,
    e.NAMA_PERISTIWA,
    e.JENIS_PERISTIWA,
    e.TINGKAT_GANGGUAN,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM MASTER_DATA.REFERENSI_PERIODE_PELAPORAN p
CROSS JOIN MASTER_DATA.INFO_DATASET i
LEFT JOIN KOLEKTE k ON k.ID_PERIODE_PELAPORAN = p.ID_PERIODE_PELAPORAN
LEFT JOIN SUMBANGAN s ON s.ID_PERIODE_PELAPORAN = p.ID_PERIODE_PELAPORAN
LEFT JOIN PENGELUARAN x ON x.ID_PERIODE_PELAPORAN = p.ID_PERIODE_PELAPORAN
LEFT JOIN PERISTIWA e ON e.ID_PERIODE_PELAPORAN = p.ID_PERIODE_PELAPORAN
WHERE p.TANGGAL_MULAI >= i.TANGGAL_MULAI_RIWAYAT
  AND p.TANGGAL_MULAI <= i.TANGGAL_SNAPSHOT;

-- 19. Income versus outcome per year ---------------------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.PEMASUKAN_PENGELUARAN_TAHUNAN
    COMMENT = 'Pemasukan dan pengeluaran program per tahun, pertumbuhan tahun ke tahun, dan kolekte per Misa tanpa peristiwa luar biasa. Tahun berjalan ditandai belum lengkap. Data simulasi.'
AS
WITH TAHUNAN AS (
    SELECT
        TAHUN,
        COUNT(*) AS JUMLAH_BULAN_TERCATAT,
        SUM(CASE WHEN STATUS_PERIODE = 'Lengkap' THEN 1 ELSE 0 END) AS JUMLAH_BULAN_LENGKAP,
        SUM(PEMASUKAN_KOLEKTE) AS PEMASUKAN_KOLEKTE,
        SUM(PEMASUKAN_SUMBANGAN_KHUSUS) AS PEMASUKAN_SUMBANGAN_KHUSUS,
        SUM(TOTAL_PEMASUKAN) AS TOTAL_PEMASUKAN,
        SUM(PENGELUARAN_PROGRAM) AS PENGELUARAN_PROGRAM
    FROM ANALISIS.PEMASUKAN_PENGELUARAN_BULANAN
    GROUP BY TAHUN
),
KOLEKTE_PER_MISA AS (
    SELECT ID_KEJADIAN_MISA,
           SUM(COALESCE(JUMLAH_HASIL_PENGHITUNGAN, JUMLAH_PENERIMAAN)) AS TOTAL_KOLEKTE
    FROM DATA_OPERASIONAL.PENERIMAAN_KOLEKTE
    GROUP BY ID_KEJADIAN_MISA
),
MISA AS (
    SELECT
        EXTRACT(YEAR FROM k.TANGGAL_MISA) AS TAHUN,
        COUNT(*) AS JUMLAH_MISA_TERLAKSANA,
        AVG(c.TOTAL_KOLEKTE) AS KOLEKTE_RATA_RATA_PER_MISA,
        AVG(CASE WHEN a.ID_PERISTIWA IS NULL THEN c.TOTAL_KOLEKTE END) AS KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA
    FROM DATA_OPERASIONAL.KEJADIAN_MISA k
    JOIN DATA_OPERASIONAL.KEHADIRAN_MISA a
        ON a.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    JOIN KOLEKTE_PER_MISA c
        ON c.ID_KEJADIAN_MISA = k.ID_KEJADIAN_MISA
    WHERE k.STATUS_PELAKSANAAN = 'Terlaksana'
    GROUP BY EXTRACT(YEAR FROM k.TANGGAL_MISA)
),
PROGRAM AS (
    SELECT TAHUN_RENCANA AS TAHUN,
           SUM(CASE WHEN STATUS_PELAKSANAAN = 'Terlaksana' THEN 1 ELSE 0 END) AS JUMLAH_KEGIATAN_TERLAKSANA,
           SUM(CASE WHEN STATUS_PELAKSANAAN <> 'Dibatalkan' THEN ANGGARAN_RENCANA ELSE 0 END) AS ANGGARAN_PROGRAM
    FROM ANALISIS.ANGGARAN_VS_REALISASI_PROGRAM
    GROUP BY TAHUN_RENCANA
),
GABUNG AS (
    SELECT
        t.TAHUN,
        t.JUMLAH_BULAN_TERCATAT,
        CASE WHEN t.JUMLAH_BULAN_LENGKAP = 12 THEN TRUE ELSE FALSE END AS TAHUN_LENGKAP,
        t.PEMASUKAN_KOLEKTE,
        t.PEMASUKAN_SUMBANGAN_KHUSUS,
        t.TOTAL_PEMASUKAN,
        t.PENGELUARAN_PROGRAM,
        p.ANGGARAN_PROGRAM,
        p.JUMLAH_KEGIATAN_TERLAKSANA,
        m.JUMLAH_MISA_TERLAKSANA,
        ROUND(m.KOLEKTE_RATA_RATA_PER_MISA, 0) AS KOLEKTE_RATA_RATA_PER_MISA,
        ROUND(m.KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA, 0) AS KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA
    FROM TAHUNAN t
    LEFT JOIN PROGRAM p ON p.TAHUN = t.TAHUN
    LEFT JOIN MISA m ON m.TAHUN = t.TAHUN
),
DENGAN_PEMBANDING AS (
    SELECT
        g.*,
        LAG(g.PEMASUKAN_KOLEKTE) OVER (ORDER BY g.TAHUN) AS KOLEKTE_TAHUN_SEBELUMNYA,
        LAG(g.PENGELUARAN_PROGRAM) OVER (ORDER BY g.TAHUN) AS PENGELUARAN_TAHUN_SEBELUMNYA,
        LAG(g.KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA) OVER (ORDER BY g.TAHUN) AS KOLEKTE_PER_MISA_TANPA_PERISTIWA_SEBELUMNYA,
        LAG(g.TAHUN_LENGKAP) OVER (ORDER BY g.TAHUN) AS TAHUN_SEBELUMNYA_LENGKAP
    FROM GABUNG g
)
SELECT
    TAHUN,
    CASE WHEN TAHUN_LENGKAP THEN 'Tahun lengkap'
         ELSE 'Tahun berjalan (' || CAST(JUMLAH_BULAN_TERCATAT AS VARCHAR) || ' bulan pertama)' END AS STATUS_TAHUN,
    TAHUN_LENGKAP,
    JUMLAH_MISA_TERLAKSANA,
    PEMASUKAN_KOLEKTE,
    PEMASUKAN_SUMBANGAN_KHUSUS,
    TOTAL_PEMASUKAN,
    PENGELUARAN_PROGRAM,
    ANGGARAN_PROGRAM,
    JUMLAH_KEGIATAN_TERLAKSANA,
    PEMASUKAN_KOLEKTE - PENGELUARAN_PROGRAM AS SELISIH_KOLEKTE_VS_PENGELUARAN,
    TOTAL_PEMASUKAN - PENGELUARAN_PROGRAM AS SELISIH_TOTAL,
    ROUND(100.0 * PENGELUARAN_PROGRAM / NULLIF(PEMASUKAN_KOLEKTE, 0), 1) AS PERSEN_PENGELUARAN_TERHADAP_KOLEKTE,
    CASE WHEN TAHUN_LENGKAP AND TAHUN_SEBELUMNYA_LENGKAP AND KOLEKTE_TAHUN_SEBELUMNYA > 0
         THEN ROUND(100.0 * (PEMASUKAN_KOLEKTE - KOLEKTE_TAHUN_SEBELUMNYA) / KOLEKTE_TAHUN_SEBELUMNYA, 1) END AS PERTUMBUHAN_KOLEKTE_PERSEN,
    CASE WHEN TAHUN_LENGKAP AND TAHUN_SEBELUMNYA_LENGKAP AND PENGELUARAN_TAHUN_SEBELUMNYA > 0
         THEN ROUND(100.0 * (PENGELUARAN_PROGRAM - PENGELUARAN_TAHUN_SEBELUMNYA) / PENGELUARAN_TAHUN_SEBELUMNYA, 1) END AS PERTUMBUHAN_PENGELUARAN_PERSEN,
    KOLEKTE_RATA_RATA_PER_MISA,
    KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA,
    CASE WHEN KOLEKTE_PER_MISA_TANPA_PERISTIWA_SEBELUMNYA > 0
         THEN ROUND(100.0 * (KOLEKTE_RATA_RATA_PER_MISA_TANPA_PERISTIWA - KOLEKTE_PER_MISA_TANPA_PERISTIWA_SEBELUMNYA)
                    / KOLEKTE_PER_MISA_TANPA_PERISTIWA_SEBELUMNYA, 1) END AS PERTUMBUHAN_KOLEKTE_PER_MISA_TANPA_PERISTIWA_PERSEN,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DENGAN_PEMBANDING;

-- 20. Trendlines and projection of income versus outcome ---------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.PROYEKSI_PEMASUKAN_PENGELUARAN
    COMMENT = 'Garis tren linear dari tahun-tahun lengkap dan proyeksinya ke depan, serta tahun ketika tren pengeluaran melampaui tren kolekte. Metode sederhana. Data simulasi.'
AS
WITH LENGKAP AS (
    SELECT TAHUN, PEMASUKAN_KOLEKTE, TOTAL_PEMASUKAN, PENGELUARAN_PROGRAM
    FROM ANALISIS.PEMASUKAN_PENGELUARAN_TAHUNAN
    WHERE TAHUN_LENGKAP = TRUE
),
GARIS AS (
    SELECT
        MAX(TAHUN) AS TAHUN_LENGKAP_TERAKHIR,
        COUNT(*) AS JUMLAH_TAHUN_DASAR,
        REGR_SLOPE(PEMASUKAN_KOLEKTE, TAHUN) AS KEMIRINGAN_KOLEKTE,
        REGR_INTERCEPT(PEMASUKAN_KOLEKTE, TAHUN) AS TITIK_AWAL_KOLEKTE,
        REGR_SLOPE(TOTAL_PEMASUKAN, TAHUN) AS KEMIRINGAN_PEMASUKAN,
        REGR_INTERCEPT(TOTAL_PEMASUKAN, TAHUN) AS TITIK_AWAL_PEMASUKAN,
        REGR_SLOPE(PENGELUARAN_PROGRAM, TAHUN) AS KEMIRINGAN_PENGELUARAN,
        REGR_INTERCEPT(PENGELUARAN_PROGRAM, TAHUN) AS TITIK_AWAL_PENGELUARAN
    FROM LENGKAP
),
DAFTAR_TAHUN AS (
    SELECT TAHUN FROM ANALISIS.PEMASUKAN_PENGELUARAN_TAHUNAN
    UNION
    SELECT g.TAHUN_LENGKAP_TERAKHIR + h.N
    FROM GARIS g
    CROSS JOIN (VALUES (1), (2), (3), (4), (5)) AS h (N)
),
HITUNG AS (
    SELECT
        y.TAHUN,
        a.TAHUN_LENGKAP,
        a.PEMASUKAN_KOLEKTE AS KOLEKTE_AKTUAL,
        a.TOTAL_PEMASUKAN AS TOTAL_PEMASUKAN_AKTUAL,
        a.PENGELUARAN_PROGRAM AS PENGELUARAN_AKTUAL,
        g.TAHUN_LENGKAP_TERAKHIR,
        g.JUMLAH_TAHUN_DASAR,
        ROUND(g.KEMIRINGAN_KOLEKTE * y.TAHUN + g.TITIK_AWAL_KOLEKTE, 0) AS KOLEKTE_TREN,
        ROUND(g.KEMIRINGAN_PEMASUKAN * y.TAHUN + g.TITIK_AWAL_PEMASUKAN, 0) AS TOTAL_PEMASUKAN_TREN,
        ROUND(g.KEMIRINGAN_PENGELUARAN * y.TAHUN + g.TITIK_AWAL_PENGELUARAN, 0) AS PENGELUARAN_TREN,
        ROUND(g.KEMIRINGAN_KOLEKTE, 0) AS PERTAMBAHAN_KOLEKTE_PER_TAHUN,
        ROUND(g.KEMIRINGAN_PENGELUARAN, 0) AS PERTAMBAHAN_PENGELUARAN_PER_TAHUN
    FROM DAFTAR_TAHUN y
    CROSS JOIN GARIS g
    LEFT JOIN ANALISIS.PEMASUKAN_PENGELUARAN_TAHUNAN a ON a.TAHUN = y.TAHUN
)
SELECT
    h.TAHUN,
    CASE WHEN h.TAHUN <= h.TAHUN_LENGKAP_TERAKHIR THEN 'Aktual (tahun lengkap)'
         WHEN h.KOLEKTE_AKTUAL IS NOT NULL THEN 'Tahun berjalan (sebagian) dan proyeksi'
         ELSE 'Proyeksi' END AS JENIS_DATA,
    h.KOLEKTE_AKTUAL,
    h.TOTAL_PEMASUKAN_AKTUAL,
    h.PENGELUARAN_AKTUAL,
    h.KOLEKTE_TREN,
    h.TOTAL_PEMASUKAN_TREN,
    h.PENGELUARAN_TREN,
    h.KOLEKTE_TREN - h.PENGELUARAN_TREN AS SELISIH_TREN_KOLEKTE_VS_PENGELUARAN,
    h.TOTAL_PEMASUKAN_TREN - h.PENGELUARAN_TREN AS SELISIH_TREN_TOTAL_PEMASUKAN_VS_PENGELUARAN,
    CASE WHEN h.PENGELUARAN_TREN > h.KOLEKTE_TREN THEN TRUE ELSE FALSE END AS TREN_PENGELUARAN_MELEBIHI_KOLEKTE,
    MIN(CASE WHEN h.TAHUN > h.TAHUN_LENGKAP_TERAKHIR AND h.PENGELUARAN_TREN > h.KOLEKTE_TREN THEN h.TAHUN END) OVER ()
        AS TAHUN_PERTAMA_PENGELUARAN_MELEBIHI_KOLEKTE,
    MIN(CASE WHEN h.TAHUN > h.TAHUN_LENGKAP_TERAKHIR AND h.PENGELUARAN_TREN > h.TOTAL_PEMASUKAN_TREN THEN h.TAHUN END) OVER ()
        AS TAHUN_PERTAMA_PENGELUARAN_MELEBIHI_TOTAL_PEMASUKAN,
    h.PERTAMBAHAN_KOLEKTE_PER_TAHUN,
    h.PERTAMBAHAN_PENGELUARAN_PER_TAHUN,
    h.JUMLAH_TAHUN_DASAR,
    'Proyeksi garis lurus (regresi linear) dari tahun-tahun lengkap. Sederhana: tidak memperhitungkan peristiwa luar biasa maupun percepatan biaya.' AS CATATAN_METODE,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM HITUNG h;

-- 21. Donations per community: economic capacity, mean, median, total, per household -----------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.SUMBANGAN_KELUARGA_PER_LINGKUNGAN
    COMMENT = 'Sumbangan kampanye per lingkungan: total, rata-rata, median, dan per keluarga atau umat terdaftar, beserta kapasitas ekonomi lingkungan. Menggambarkan sebaran, bukan menilai iman atau kemurahan hati. Data simulasi.'
AS
WITH KAMPANYE AS (
    SELECT k.ID_KAMPANYE, k.NAMA_KAMPANYE, k.PERIODE_MULAI, k.PERIODE_SELESAI, k.STATUS_KAMPANYE,
           LEAST(k.PERIODE_SELESAI, i.TANGGAL_SNAPSHOT) AS TANGGAL_ACUAN
    FROM DATA_OPERASIONAL.KAMPANYE_SUMBANGAN k
    CROSS JOIN MASTER_DATA.INFO_DATASET i
),
TERDAFTAR AS (
    SELECT k.ID_KAMPANYE, pl.ID_LINGKUNGAN,
           COUNT(DISTINCT pl.ID_KELUARGA) AS JUMLAH_KELUARGA_TERDAFTAR,
           COUNT(DISTINCT pk.ID_UMAT) AS JUMLAH_UMAT_TERDAFTAR
    FROM KAMPANYE k
    JOIN DATA_OPERASIONAL.PENUGASAN_LINGKUNGAN pl
        ON pl.TANGGAL_MULAI_BERLAKU <= k.TANGGAL_ACUAN
       AND (pl.TANGGAL_AKHIR_BERLAKU IS NULL OR pl.TANGGAL_AKHIR_BERLAKU >= k.TANGGAL_ACUAN)
    LEFT JOIN DATA_OPERASIONAL.PENUGASAN_KELUARGA pk
        ON pk.ID_KELUARGA = pl.ID_KELUARGA
       AND pk.TANGGAL_MULAI_BERLAKU <= k.TANGGAL_ACUAN
       AND (pk.TANGGAL_AKHIR_BERLAKU IS NULL OR pk.TANGGAL_AKHIR_BERLAKU >= k.TANGGAL_ACUAN)
    GROUP BY k.ID_KAMPANYE, pl.ID_LINGKUNGAN
),
SUMBANGAN AS (
    SELECT ID_KAMPANYE, ID_LINGKUNGAN,
           COUNT(*) AS JUMLAH_KELUARGA_PENYUMBANG,
           SUM(JUMLAH_SUMBANGAN) AS TOTAL_SUMBANGAN,
           AVG(JUMLAH_SUMBANGAN) AS RATA_RATA,
           MEDIAN(JUMLAH_SUMBANGAN) AS MEDIAN_SUMBANGAN,
           MAX(JUMLAH_SUMBANGAN) AS SUMBANGAN_TERBESAR
    FROM DATA_OPERASIONAL.SUMBANGAN_KELUARGA
    GROUP BY ID_KAMPANYE, ID_LINGKUNGAN
)
SELECT
    k.ID_KAMPANYE,
    k.NAMA_KAMPANYE,
    EXTRACT(YEAR FROM k.PERIODE_MULAI) AS TAHUN,
    w.NAMA_WILAYAH,
    l.ID_LINGKUNGAN,
    l.NAMA_LINGKUNGAN,
    pe.KATEGORI_EKONOMI,
    pe.INDEKS_KAPASITAS_EKONOMI,
    t.JUMLAH_KELUARGA_TERDAFTAR,
    t.JUMLAH_UMAT_TERDAFTAR,
    s.JUMLAH_KELUARGA_PENYUMBANG,
    s.TOTAL_SUMBANGAN,
    ROUND(s.RATA_RATA, 0) AS RATA_RATA_PER_KELUARGA_PENYUMBANG,
    ROUND(s.MEDIAN_SUMBANGAN, 0) AS MEDIAN_PER_KELUARGA_PENYUMBANG,
    ROUND(100.0 * (s.RATA_RATA - s.MEDIAN_SUMBANGAN) / NULLIF(s.MEDIAN_SUMBANGAN, 0), 1) AS SELISIH_RATA_RATA_DARI_MEDIAN_PERSEN,
    ROUND(100.0 * s.SUMBANGAN_TERBESAR / NULLIF(s.TOTAL_SUMBANGAN, 0), 1) AS PERSEN_TOTAL_DARI_SUMBANGAN_TERBESAR,
    ROUND(1.0 * s.TOTAL_SUMBANGAN / NULLIF(t.JUMLAH_KELUARGA_TERDAFTAR, 0), 0) AS SUMBANGAN_PER_KELUARGA_TERDAFTAR,
    ROUND(1.0 * s.TOTAL_SUMBANGAN / NULLIF(t.JUMLAH_UMAT_TERDAFTAR, 0), 0) AS SUMBANGAN_PER_UMAT_TERDAFTAR,
    'Menggambarkan kapasitas ekonomi dan sebaran sumbangan, bukan tingkat iman atau kemurahan hati. Jangan dipakai untuk memeringkat lingkungan.' AS CATATAN_PENGGUNAAN,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM SUMBANGAN s
JOIN KAMPANYE k ON k.ID_KAMPANYE = s.ID_KAMPANYE
JOIN MASTER_DATA.MASTER_LINGKUNGAN l ON l.ID_LINGKUNGAN = s.ID_LINGKUNGAN
JOIN MASTER_DATA.MASTER_WILAYAH w ON w.ID_WILAYAH = l.ID_WILAYAH
JOIN MASTER_DATA.PROFIL_EKONOMI_LINGKUNGAN pe ON pe.ID_LINGKUNGAN = l.ID_LINGKUNGAN
LEFT JOIN TERDAFTAR t ON t.ID_KAMPANYE = s.ID_KAMPANYE AND t.ID_LINGKUNGAN = s.ID_LINGKUNGAN;

-- 22. Break-even: does a campaign cover the celebration it pays for? ----------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.TITIK_IMPAS_KAMPANYE
    COMMENT = 'Sumbangan kampanye (Prapaskah, Adven, solidaritas) dibandingkan dengan biaya kegiatan besar yang didanainya, per tahun. Surplus menjadi pemasukan gereja, defisit ditutup gereja. Data simulasi.'
AS
WITH SUMBANGAN AS (
    SELECT ID_KAMPANYE, COUNT(*) AS JUMLAH_KELUARGA_PENYUMBANG, SUM(JUMLAH_SUMBANGAN) AS TOTAL_SUMBANGAN
    FROM DATA_OPERASIONAL.SUMBANGAN_KELUARGA
    GROUP BY ID_KAMPANYE
)
SELECT
    k.ID_KAMPANYE,
    k.NAMA_KAMPANYE,
    EXTRACT(YEAR FROM k.PERIODE_MULAI) AS TAHUN,
    o.NAMA_KESEMPATAN,
    k.STATUS_KAMPANYE,
    k.TARGET_DANA,
    COALESCE(s.JUMLAH_KELUARGA_PENYUMBANG, 0) AS JUMLAH_KELUARGA_PENYUMBANG,
    COALESCE(s.TOTAL_SUMBANGAN, 0) AS TOTAL_SUMBANGAN,
    p.NAMA_PROGRAM AS KEGIATAN_YANG_DIDANAI,
    p.STATUS_PELAKSANAAN AS STATUS_KEGIATAN,
    p.ANGGARAN_RENCANA,
    p.ANGGARAN_TERPAKAI AS BIAYA_AKTUAL,
    CASE WHEN p.STATUS_PELAKSANAAN = 'Terlaksana' THEN COALESCE(s.TOTAL_SUMBANGAN, 0) - p.ANGGARAN_TERPAKAI END AS SELISIH_SUMBANGAN_VS_BIAYA_AKTUAL,
    CASE WHEN p.STATUS_PELAKSANAAN = 'Terlaksana' AND p.ANGGARAN_TERPAKAI > 0
         THEN ROUND(100.0 * COALESCE(s.TOTAL_SUMBANGAN, 0) / p.ANGGARAN_TERPAKAI, 1) END AS PERSEN_BIAYA_TERTUTUP_SUMBANGAN,
    CASE WHEN p.STATUS_PELAKSANAAN = 'Terlaksana' AND COALESCE(s.TOTAL_SUMBANGAN, 0) >= p.ANGGARAN_TERPAKAI
         THEN COALESCE(s.TOTAL_SUMBANGAN, 0) - p.ANGGARAN_TERPAKAI END AS PEMASUKAN_BERSIH_UNTUK_GEREJA,
    CASE WHEN p.STATUS_PELAKSANAAN = 'Terlaksana' AND COALESCE(s.TOTAL_SUMBANGAN, 0) < p.ANGGARAN_TERPAKAI
         THEN p.ANGGARAN_TERPAKAI - COALESCE(s.TOTAL_SUMBANGAN, 0) END AS DANA_TAMBAHAN_DARI_GEREJA,
    CASE WHEN p.ID_RENCANA IS NULL THEN 'Tidak ada kegiatan yang didanai'
         WHEN p.STATUS_PELAKSANAAN <> 'Terlaksana' THEN 'Belum dapat dihitung (kegiatan belum terlaksana)'
         WHEN COALESCE(s.TOTAL_SUMBANGAN, 0) >= p.ANGGARAN_TERPAKAI THEN 'Surplus: kelebihan dana menjadi pemasukan gereja'
         ELSE 'Defisit: gereja perlu menambah dana'
    END AS STATUS_TITIK_IMPAS,
    CASE WHEN p.STATUS_PELAKSANAAN <> 'Terlaksana' THEN k.TARGET_DANA - p.ANGGARAN_RENCANA END AS PROYEKSI_SELISIH_JIKA_TARGET_TERCAPAI,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM DATA_OPERASIONAL.KAMPANYE_SUMBANGAN k
JOIN MASTER_DATA.REFERENSI_KESEMPATAN_KHUSUS o
    ON o.ID_KESEMPATAN = k.ID_KESEMPATAN
LEFT JOIN SUMBANGAN s
    ON s.ID_KAMPANYE = k.ID_KAMPANYE
LEFT JOIN ANALISIS.ANGGARAN_VS_REALISASI_PROGRAM p
    ON p.ID_RENCANA = k.ID_RENCANA_PENGGUNAAN;

-- 23. Upcoming activities: from the annual plan to a scheduled event -------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ANALISIS.KEGIATAN_MENDATANG
    COMMENT = 'Kegiatan yang akan datang, satu baris per rencana yang belum terlaksana: sudah dijadwalkan sebagai kegiatan, masih berupa rencana tahunan, atau ditunda tahun ini dan perlu jadwal baru. Lengkap dengan tanggal, tempat, target peserta, anggaran, dan dana pendukung. Acuan waktu adalah tanggal data. Data simulasi.'
AS
WITH DANA AS (
    SELECT ID_RENCANA_PENGGUNAAN AS ID_RENCANA,
           MIN(NAMA_KAMPANYE) AS NAMA_KAMPANYE,
           SUM(TARGET_DANA) AS TARGET_DANA
    FROM DATA_OPERASIONAL.KAMPANYE_SUMBANGAN
    WHERE ID_RENCANA_PENGGUNAAN IS NOT NULL
    GROUP BY ID_RENCANA_PENGGUNAAN
)
SELECT
    p.ID_RENCANA,
    p.TAHUN_RENCANA,
    p.ID_SEKSI,
    p.NAMA_SEKSI,
    p.NAMA_PROGRAM,
    CASE WHEN p.STATUS_PELAKSANAAN = 'Ditunda' THEN 'Ditunda, perlu jadwal baru'
         WHEN g.ID_KEGIATAN IS NOT NULL THEN 'Sudah dijadwalkan'
         ELSE 'Masih rencana tahunan'
    END AS TAHAP,
    p.STATUS_PELAKSANAAN AS STATUS_RENCANA,
    g.ID_KEGIATAN,
    COALESCE(g.TANGGAL_MULAI, p.TANGGAL_RENCANA) AS TANGGAL_MULAI,
    COALESCE(g.TANGGAL_SELESAI, p.TANGGAL_RENCANA) AS TANGGAL_SELESAI,
    DATEDIFF('day', i.TANGGAL_SNAPSHOT, COALESCE(g.TANGGAL_MULAI, p.TANGGAL_RENCANA)) AS HARI_DARI_TANGGAL_DATA,
    g.LOKASI,
    g.TARGET_PESERTA,
    p.ANGGARAN_RENCANA,
    g.KETERANGAN AS CATATAN_KEGIATAN,
    d.NAMA_KAMPANYE AS DIDANAI_KAMPANYE,
    d.TARGET_DANA AS TARGET_DANA_KAMPANYE,
    CASE WHEN d.ID_RENCANA IS NOT NULL THEN d.TARGET_DANA - p.ANGGARAN_RENCANA END AS SELISIH_TARGET_DANA_VS_ANGGARAN,
    i.TANGGAL_SNAPSHOT AS TANGGAL_DATA,
    'Data simulasi (fiktif)' AS SUMBER_DATA
FROM ANALISIS.ANGGARAN_VS_REALISASI_PROGRAM p
CROSS JOIN MASTER_DATA.INFO_DATASET i
LEFT JOIN DATA_OPERASIONAL.KEGIATAN g
    ON g.ID_RENCANA = p.ID_RENCANA
LEFT JOIN DANA d
    ON d.ID_RENCANA = p.ID_RENCANA
WHERE p.STATUS_PELAKSANAAN = 'Direncanakan'
   OR (p.STATUS_PELAKSANAAN = 'Ditunda' AND p.TAHUN_RENCANA = EXTRACT(YEAR FROM i.TANGGAL_SNAPSHOT));
